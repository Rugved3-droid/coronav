def user_msg_biplane(retractions_remaining, no_progress_advances,
                     current_dist, dist_trend):
    """Minimal change from user_msg: prefix identifies two images."""
    parts = [
        "Biplane views (two images attached).",
        f"Retractions remaining: {retractions_remaining} of {RETRACTION_BUDGET}.",
        f"Consecutive no-progress advance steps: {no_progress_advances}.",
        f"Current distance to mid-LAD target: {current_dist:.1f} mm.",
        f"Distance trend (last 3 steps): {dist_trend}.",
    ]
    if no_progress_advances >= 3:
        parts.append(
            f"WARNING: {no_progress_advances} consecutive advance steps with no progress -- "
            "you MUST rotate on this step."
        )
    if _gate_active(current_dist, dist_trend):
        parts.append(
            f"PROXIMITY GATE ACTIVE: distance is under {PROXIMITY_GATE_DIST_MM:.0f}mm "
            f"and decreasing -- do NOT rotate, output advance "
            f"(translation={PROXIMITY_GATE_ADV_DEFAULT:.1f})."
        )
    parts.append("Navigate the wire to the mid-LAD target.")
    return " ".join(parts)


# ── VLM call (biplane: two images) ────────────────────────────────────────────
def call_vlm_biplane(client, b64_a: str, b64_b: str,
                     retractions_remaining: int, no_progress: int,
                     current_dist: float, dist_trend: str) -> str:
    response = client.messages.create(
        model=MODEL, max_tokens=600, system=SYSTEM_PROMPT_BIPLANE,
        messages=[{"role": "user", "content": [
            {"type": "image", "source": {"type": "base64",
                                         "media_type": "image/png",
                                         "data": b64_a}},
            {"type": "image", "source": {"type": "base64",
                                         "media_type": "image/png",
                                         "data": b64_b}},
            {"type": "text", "text": user_msg_biplane(
                retractions_remaining, no_progress, current_dist, dist_trend)},
        ]}],
    )
    return response.content[0].text


